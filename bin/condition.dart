void main(List<String> args) {
  const number = 124;

  if (number > 100) {
    print('Number is greater than 100');
  } else if (number > 120) {
    print('Number is greater than 120');
  } else if (number > 150) {
    print('Number is greater than 150');
  } else {
    print('The number is: $number');
  }
}